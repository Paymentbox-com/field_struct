# frozen_string_literal: true

module FieldStruct
  # Generates RBS type signatures for the *generated* instance surface of
  # user-defined {FieldStruct::Base} subclasses — the per-field accessors the
  # +field+ DSL defines dynamically.
  #
  # Sord generates +sig/field_struct.rbs+ from the library's static source, so
  # it covers {Base}, {Types}, {Registry}, … but it can never see +User#name+
  # or +User#age=+: those methods don't exist until a consumer declares the
  # fields. This is the deferred "track 2" of the plan's RBS strategy (D13) —
  # walk a subclass's {Metadata} and emit signatures for its accessors so
  # downstream Steep / Solargraph can type-check code that touches them.
  #
  #   class User < FieldStruct::Base
  #     required :name, :string
  #     optional :age,  :integer
  #   end
  #
  #   puts FieldStruct::RBS.generate(User)
  #   # # Generated by FieldStruct::RBS. ...
  #   # class User < ::FieldStruct::Base
  #   #   attr_reader name: ::String
  #   #   def name=: (::String? value) -> ::String?
  #   #
  #   #   attr_reader age: ::Integer?
  #   #   def age=: (::Integer? value) -> ::Integer?
  #   # end
  #
  # Design choices:
  #
  # * **Types describe a valid instance.** The reader type is the field's
  #   {Types::Base#ruby_type} (or an override, below). Nullability follows
  #   {Field#required?}: required → +T+, optional → +T?+. An invalid
  #   instance — a required field left unset, or a +:keep_raw+ coercion
  #   failure holding the raw input — can hold other values; check +valid?+
  #   before trusting the signature. The generated header says so.
  # * **Writer** is +(T? value) -> T?+: the runtime setter accepts +nil+ and
  #   returns the coerced value. Loose input the type would coerce
  #   (+user.age = "30"+) is valid Ruby but a type error to Steep — cast or
  #   coerce at the boundary.
  # * **Generic arguments** are filled in: arrays as +::Array[Element]+,
  #   unions as +(A | B)+ (a boolean member as +bool+), nested structs by
  #   qualified name. A custom type whose +ruby_type+ is a bare generic
  #   class (+::Hash+) gets +untyped+ arguments unless it declares
  #   {Types::Base#rbs_type}.
  # * **Anything-valued fields** (+:value+, or a union with a +:value+
  #   member) are +untyped+ — reader and writer, never +untyped?+.
  # * **Overrides:** a field's +rbs_type:+ option, then the type's
  #   {Types::Base#rbs_type}, replace the derived type +T+ verbatim;
  #   nullability is still added for optional fields and writers.
  # * **+new+ / +initialize+** are inherited from {Base}, which already
  #   accepts +User.new(name: ...)+.
  #
  # Each call emits one class. Referenced types (nested structs, array
  # elements) appear as qualified names (+::Address+) — generate RBS for those
  # classes too so the references resolve. {.type_for} exposes the per-field
  # mapping for other generators.
  module RBS
    # The pair a +:boolean+ field's +ruby_type+ returns, rendered as +bool+.
    # @return [Array<Class>]
    BOOL_CLASSES = [TrueClass, FalseClass].freeze
    private_constant :BOOL_CLASSES

    # Comment lines opening every {.generate} result: the contract the
    # signatures hold to.
    # @return [String]
    HEADER = <<~RBS
      # Generated by FieldStruct::RBS. Types describe a valid instance: an
      # invalid one (a required field left unset, or a :keep_raw coercion
      # failure holding the raw input) can hold other values. Check valid?.
    RBS
    private_constant :HEADER

    # Ruby classes RBS declares with type parameters, and how many. A bare
    # +ruby_type+ naming one of these is emitted with +untyped+ arguments,
    # since RBS rejects a generic class without them.
    # @return [Hash{Class=>Integer}]
    GENERIC_ARITY = {::Array => 1, ::Hash => 2, ::Range => 1}.freeze
    private_constant :GENERIC_ARITY

    # Generate RBS source for a single FieldStruct subclass.
    #
    # @param klass [Class<FieldStruct::Base>]
    # @return [String] RBS declaring the class (wrapped in its module nesting)
    #   and a typed reader and writer for every field it declares, after a
    #   comment header stating that the types describe a valid instance
    # @raise [ArgumentError] when +klass+ is not a named {FieldStruct::Base}
    #   subclass
    def self.generate(klass)
      unless klass.is_a?(::Class) && klass < FieldStruct::Base
        raise ArgumentError,
          "FieldStruct::RBS.generate expects a FieldStruct::Base subclass, got #{klass.inspect}"
      end
      raise ArgumentError, 'cannot generate RBS for an anonymous class' unless klass.name

      HEADER + wrap_namespace(klass.name, class_block(klass))
    end

    # The RBS type of one field's value, as {.generate} emits it — for other
    # generators (e.g. one typing a method that takes or returns the field)
    # that need the same mapping:
    #
    #   FieldStruct::RBS.type_for(Order.metadata[:items])
    #   # => "::Array[::LineItem]?"
    #   FieldStruct::RBS.type_for(Order.metadata[:items], nullable: false)
    #   # => "::Array[::LineItem]"
    #
    # The type comes from the field's +rbs_type:+ option, else its type's
    # {Types::Base#rbs_type}, else its {Types::Base#ruby_type} with generic
    # arguments filled in. Qualified names (+::LineItem+) assume the
    # referenced classes get RBS too.
    #
    # @param field [Field] a declared field, e.g. +Order.metadata[:items]+
    # @param nullable [Boolean, nil] append +?+ (the reader type of an
    #   optional field, and every writer's); +nil+, the default, means
    #   +!field.required?+. Never applied to +untyped+, which already
    #   admits +nil+.
    # @return [String] an RBS type expression
    # @raise [ArgumentError] when +field+ is not a {Field}
    def self.type_for(field, nullable: nil)
      unless field.is_a?(FieldStruct::Field)
        raise ArgumentError, 'FieldStruct::RBS.type_for expects a FieldStruct::Field ' \
                             "(e.g. User.metadata[:name]), got #{field.inspect}"
      end

      nullable = !field.required? if nullable.nil?
      base = override_expression(field.rbs_type || field.type_instance.rbs_type) ||
        expression_for(field.type_instance, field.options)
      nullable ? optional(base) : base
    end

    # Build the +class ... end+ block (unindented, no surrounding modules).
    #
    # @param klass [Class<FieldStruct::Base>]
    # @return [String]
    def self.class_block(klass)
      simple = klass.name.split('::').last
      lines = ["class #{simple} < ::#{klass.superclass.name}"]
      own_fields(klass).each_with_index do |field, index|
        writer = type_for(field, nullable: true)
        lines << '' unless index.zero?
        lines << "  attr_reader #{field.name}: #{type_for(field)}"
        lines << "  def #{field.name}=: (#{writer} value) -> #{writer}"
      end
      lines << 'end'
      lines.join("\n")
    end
    private_class_method :class_block

    # Fields declared on +klass+ itself — inherited fields (the same {Field}
    # objects merged in at inheritance time) belong to the parent's RBS.
    #
    # @param klass [Class<FieldStruct::Base>]
    # @return [Array<Field>]
    def self.own_fields(klass)
      parent = klass.superclass
      parent_meta = parent.respond_to?(:metadata) ? parent.metadata : nil
      klass.metadata.reject { |field| parent_meta && parent_meta[field.name].equal?(field) }
    end
    private_class_method :own_fields

    # An override, parenthesized when it is a union, intersection or proc
    # type, so a trailing +?+ applies to the whole of it.
    #
    # @param rbs [String, nil] a field's +rbs_type:+ or a type's +rbs_type+
    # @return [String, nil] +nil+ when there is no override
    def self.override_expression(rbs)
      return nil if rbs.nil?

      rbs = rbs.strip
      rbs.match?(/[|&^]/) ? "(#{rbs})" : rbs
    end
    private_class_method :override_expression

    # @param base [String] an RBS type expression
    # @return [String] +base+ made nullable, unless it already admits +nil+
    def self.optional(base)
      return base if base == 'untyped' || base.end_with?('?')

      "#{base}?"
    end
    private_class_method :optional

    # Map a type instance (plus its field options, needed for arrays) to an
    # RBS type expression.
    #
    # @param type_instance [Types::Base]
    # @param options [Hash{Symbol=>Object, nil}]
    # @return [String]
    def self.expression_for(type_instance, options)
      return "::Array[#{element_type(options[:of_type])}]" if type_instance.is_a?(FieldStruct::Types::Array)

      ruby_type = type_instance.ruby_type
      classes = ruby_type.is_a?(::Array) ? ruby_type : [ruby_type]
      mapped = classes_to_rbs(classes)
      return 'untyped' if mapped.include?('untyped')

      mapped.one? ? mapped.first : "(#{mapped.join(" | ")})"
    end
    private_class_method :expression_for

    # @param classes [Array<Class>] a {Types::Base#ruby_type}, as a list
    # @return [Array<String>] one RBS type per class, with +TrueClass+ /
    #   +FalseClass+ together collapsed to +bool+ where the pair appears
    def self.classes_to_rbs(classes)
      bool = BOOL_CLASSES.all? { |klass| classes.include?(klass) }
      classes.map { |klass| bool && BOOL_CLASSES.include?(klass) ? 'bool' : class_to_rbs(klass) }.uniq
    end
    private_class_method :classes_to_rbs

    # The element type of an array field, derived from its +:of_type+ (a
    # +Types::Base+ subclass for stock types, or a built instance for
    # parameterized ones like {Types::Nested}).
    #
    # @param of_type [Class, Types::Base, nil]
    # @return [String]
    def self.element_type(of_type)
      return 'untyped' if of_type.nil?

      instance = of_type.is_a?(::Class) ? of_type.new : of_type
      override_expression(instance.rbs_type) || expression_for(instance, {})
    end
    private_class_method :element_type

    # @param klass [Class] a Ruby class from a {Types::Base#ruby_type}
    # @return [String] qualified RBS name (with +untyped+ type arguments for
    #   a generic class), or +untyped+ for the value type's +::Object+
    def self.class_to_rbs(klass)
      return 'untyped' if klass == ::Object

      arity = GENERIC_ARITY[klass]
      return "::#{klass.name}" unless arity

      "::#{klass.name}[#{Array.new(arity, "untyped").join(", ")}]"
    end
    private_class_method :class_to_rbs

    # Wrap an inner block in the +module ... end+ nesting implied by a
    # qualified class name, indenting two spaces per level.
    #
    # @param full_name [String] e.g. +"Acme::Order"+
    # @param inner [String] the class block
    # @return [String] RBS source ending in a trailing newline
    def self.wrap_namespace(full_name, inner)
      modules = full_name.split('::')[0...-1]
      block = inner
      modules.reverse_each { |mod| block = "module #{mod}\n#{indent(block)}\nend" }
      "#{block}\n"
    end
    private_class_method :wrap_namespace

    # @param text [String]
    # @return [String] +text+ with every non-blank line indented two spaces
    def self.indent(text)
      text.split("\n", -1).map { |line| line.empty? ? line : "  #{line}" }.join("\n")
    end
    private_class_method :indent
  end
end
